import { readFile, writeFile, readdir } from 'node:fs/promises';
import path from 'node:path';
const check = process.argv.includes('--check');
const template = (await readFile('partials/primary-navigation.html', 'utf8')).trim();
const pages = [...(await readdir('.')).filter(p => p.endsWith('.html')), ...(await readdir('mysteries')).filter(p => p.endsWith('.html')).map(p => `mysteries/${p}`), ...(await readdir('miracles').catch(() => [])).filter(p => p.endsWith('.html')).map(p => `miracles/${p}`), ...(await readdir('miracles/eucharistic').catch(() => [])).filter(p => p.endsWith('.html')).map(p => `miracles/eucharistic/${p}`)];
import { renderPrimaryNav } from './lib/primary-nav.mjs';
let count = 0; const stale = [];
for (const file of pages) {
  const source = await readFile(file, 'utf8');
  // Generated international pages own their single language navigation and
  // must not be rewritten with the interactive app's primary navigation.
  if (source.includes('Generated by npm run i18n:build') || !/<header\b/.test(source)) continue;
  const navPattern = /<nav\b[^>]*class=["']links["'][^>]*>[\s\S]*?<\/nav>/;
  if (!navPattern.test(source)) throw new Error(`Missing primary navigation in ${file}`);
  const prefix = file.startsWith('miracles/eucharistic/') ? '../../' : file.includes('/') ? '../' : './';
  const nav = renderPrimaryNav(template, file);
  let updated = source.replace(navPattern, nav);
  const script = `<script src="${prefix}nav.js?v=20260922-1" defer></script>`;
  if (!/<script[^>]+src=["'][^"']*nav\.js/.test(updated)) updated = updated.replace('</body>', `  ${script}\n</body>`);
  if (updated !== source) { stale.push(file); if (!check) await writeFile(file, updated); }
  count++;
}
console.log(`${count} pages checked against shared primary navigation; ${stale.length} ${check ? 'out of sync' : 'updated'}.`);
if (stale.length) console.log(stale.join('\n'));
if (check && stale.length) process.exitCode = 1;
