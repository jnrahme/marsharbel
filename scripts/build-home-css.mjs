import { PurgeCSS } from 'purgecss';
import { transform } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

process.chdir(fileURLToPath(new URL('..', import.meta.url)));
const [result] = await new PurgeCSS().purge({
  content: ['index.html', 'app.js', 'nav.js', 'translate.js', 'global-audio-player.js'],
  css: ['styles.css'],
  // Keep runtime states and the audio controls used when returning from prayers.
  safelist: { standard: [/^is-/, /^nav-/, /^floating-audio/, /^lang-switcher/, /^sc-/] }
});
const { code } = await transform(result.css, { loader: 'css', minify: true, target: ['chrome109', 'safari16'] });
const output = '/* Generated by npm run build:home-css. Edit styles.css, not this file. */\n' + code;
if (process.argv.includes('--check')) {
  if (await readFile('home.css', 'utf8') !== output) {
    throw new Error('home.css is stale. Run npm run build:home-css.');
  }
  console.log('Homepage CSS matches its sources.');
} else {
  await writeFile('home.css', output);
  console.log(`Generated home.css: ${Buffer.byteLength(output)} bytes`);
}
