#!/usr/bin/env python3
"""Render the strict 12-locale film premiere family from the keyed English master.

The EN master (charbel-film-premiere.html) is built from src/pages; this producer
renders the 11 registered locale pages. Article bytes come from apply_keyed_master
only; the shell reuses templates/international/page.html with locale catalogs.
"""
import argparse
import html
import json
import re
import subprocess
import sys
from pathlib import Path
from string import Template
from bs4 import BeautifulSoup
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts'))
from i18n.film_master_family import FAMILY, ID, SLUG, RULE, FONT
from i18n.keyed_master import apply_keyed_master
from i18n.feature_mirror import one

def render_locale(root, registry, code):
    cfg = registry['pageMirrors'][FAMILY]
    routes = {'en': cfg['english'], **cfg['routes']}
    route = routes[code]
    site = registry['site']
    _, keyed, copy = apply_keyed_master(root, FAMILY, code)
    article = str(one(keyed, 'main > article.film-news-article'))
    common = json.loads((root / f'locales/{code}/common.json').read_text())
    url = site + route
    cluster = ''.join(f'<link rel="alternate" hreflang="{c}" href="{site + p}" />' for c, p in routes.items())
    cluster += f'<link rel="alternate" hreflang="x-default" href="{site + routes["en"]}" />'
    names = {c: registry['locales'][c]['nativeName'] for c in routes}
    switcher = f'<nav class="film-locale-switcher locale-nav" aria-label="{html.escape(common["navigation.chooseLanguage"])}">'
    switcher += ''.join(f'<a hreflang="{c}" href="{p}">{html.escape(names[c])}</a>' for c, p in routes.items())
    switcher += '</nav>'
    home_cfg = registry['locales'][code].get('home')
    home = home_cfg if home_cfg else '/'
    home_label = html.escape(common['navigation.home'])
    if not home_cfg:
        qualifier = json.loads((root / f'locales/{code}/encyclopedia-trail.json').read_text())['englishQualifier']
        home_label += ' ' + html.escape(qualifier)
    # Shared serializer owns WebPage structure; no hand-added schema block.
    args = [copy['premiere.title'], copy['premiere.body'], url,
            common['navigation.home'], site + home, copy['premiere.title'], url]
    args = [json.dumps(v, ensure_ascii=False)[1:-1].replace('<', '\\u003c').replace('&', '\\u0026') for v in args]
    script = "import {renderWebPage} from './scripts/lib/jsonld.mjs';process.stdout.write(renderWebPage(JSON.parse(process.argv[1])))"
    schema_block = subprocess.check_output(['node', '--input-type=module', '-e', script, json.dumps(args, ensure_ascii=False)], cwd=root, text=True)
    schema = re.search(r'<script[^>]*>([\s\S]*)</script>', schema_block)[1].strip()
    template = Template((root / 'templates/international/page.html').read_text())
    direction = registry['locales'][code]['direction']
    text = template.substitute(language=code, direction=direction, title=html.escape(copy['premiere.title']), description=html.escape(copy['premiere.release']), canonical=url,
        alternates=cluster, oglocale=f'<meta property="og:locale" content="{registry["locales"][code]["ogLocale"]}" />', brand=html.escape(common['site.brand']), site=site,
        schema=schema, skip=html.escape(common['navigation.skip']), home=home,
        chooseLanguage=html.escape(common['navigation.chooseLanguage']), navigation='<a href="/charbel-film-premiere" lang="en" dir="ltr">' + html.escape(registry['locales']['en']['nativeName']) + '</a>',
        homeLabel=home_label, content=switcher + article, footer=html.escape(common['site.footer']))
    text = text.replace('<!-- Generated by npm run i18n:build. Edit locales/, not this HTML. -->', f'<!-- Generated by npm run i18n:build (scripts/build_film_premiere_family.py). Edit locales/{code}/film-premiere-master-copy.json and the EN master. -->')
    text = text.replace('<link rel="stylesheet" href="/international.css', '<link rel="stylesheet" href="/styles.css?v=20261002-share-2" />\n<link rel="stylesheet" href="/international.css')
    text = text.replace('</head>', '<style>' + RULE + FONT + '</style>\n</head>')
    labels = json.loads((root / f'locales/{code}/share.json').read_text())
    text = text.replace('</head>', '<script type="application/json" id="sc-share-labels">' + json.dumps(labels, ensure_ascii=False).replace('<', '\\u003c') + '</script>\n</head>')
    text = text.replace('</body>', '<script defer src="/share.js?v=20261002-share-2" data-share-mode="page"></script>\n</body>')
    return root / (route.lstrip('/') + '.html'), text

def outputs(root=ROOT):
    registry = json.loads((root / 'locales/registry.json').read_text())
    cfg = registry['pageMirrors'][FAMILY]
    result = dict(render_locale(root, registry, code) for code in cfg['renderLocales'])
    # Own the final bytes: page_mirror families embed the runtime dictionary and
    # same-page controls themselves, so the international build's postprocess
    # pass (build-international.py) is a no-op on these pages.
    from i18n.catalog import read_json
    from i18n.runtime_labels import ensure_runtime_labels
    from i18n.same_page_injection import control_outputs
    manifest = read_json(root / 'locales/same-page-manifest.pending.json')
    control_copy = read_json(root / 'locales/same-page-copy.json')
    for path, text in list(result.items()):
        result[path] = ensure_runtime_labels(text, root, path.parent.name, registry)
    result.update(control_outputs(root, result, manifest, control_copy))
    return result

def main():
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    result = outputs()
    if args.check:
        stale = [str(p) for p, t in result.items() if not p.exists() or p.read_text() != t]
        if stale: raise SystemExit('Film premiere family stale: ' + ', '.join(stale))
    else:
        for path, text in result.items():
            path.parent.mkdir(parents=True, exist_ok=True); path.write_text(text)
if __name__ == '__main__': main()
